"""Start the API server (uvicorn) for phase7_production/app.py.

Run: uv run python -m phase7_production.01_serve                       # OpenAI backend (falls back if the API is down)
     uv run python -m phase7_production.01_serve --stub                # no LLM calls: rule plan + extractive answers
     uv run python -m phase7_production.01_serve --stub --workers 2    # 2 processes (each loads its own index + models)
Then: uv run python -m phase7_production.02_client "What was Apple's total net sales in fiscal 2025?"
      open http://localhost:8000/docs (OpenAPI UI generated by FastAPI)

One uvicorn worker = one process = one event loop plus a thread pool for the sync pipeline. Workers don't share
memory: each holds the BM25 index, the reranker and the caches, and has its own rate-limit buckets (Redis fixes both).
"""
import argparse
import os

import uvicorn


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--stub", action="store_true", help="LLM_BACKEND=stub")
    ap.add_argument("--qdrant", action="store_true", help="VECTOR_DB=qdrant")
    args = ap.parse_args()
    if args.stub:
        os.environ["LLM_BACKEND"] = "stub"
    if args.qdrant:
        os.environ["VECTOR_DB"] = "qdrant"
    uvicorn.run("phase7_production.app:app", host="127.0.0.1", port=args.port, workers=args.workers, log_level="info")


if __name__ == "__main__":
    main()
